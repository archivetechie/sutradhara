def _receive_case(
    work_root: Path,
    name: str,
    write_source: Callable[[Path], None],
) -> dict[str, Any]:
    source = work_root / "sources" / name
    landing = work_root / "landings" / name
    write_source(source)
    with _fixed_minted_intake_id(f"fixture-{name}"):
        result = receive_source(
            source,
            landing=landing,
            source_kind="card",
            operator="Op Name",
            source_ref="SRC",
            artifactclass="camera-original",
            label="fixture",
            now=FIXED_NOW,
        )
    return {
        "name": name,
        "result": _normalize_json(
            receive_cli.receive_result_payload(result, None),
            work_root=work_root,
            source=source,
            landing=landing,
            intake_id=result.intake_id,
        ),
        "validation": _validation_result_payload(validate_bag(result.intake_dir)),
        "files": _snapshot_bag_files(
            result.intake_dir,
            work_root=work_root,
            source=source,
            landing=landing,
            intake_id=result.intake_id,
        ),
    }


@contextlib.contextmanager
def _fixed_minted_intake_id(intake_id: str) -> Iterator[None]:
    original = receive_core._mint_intake_id
    receive_core._mint_intake_id = lambda _operator, _now, _landing_root: intake_id
    try:
        yield
    finally:
        receive_core._mint_intake_id = original


def _cli_case(work_root: Path, name: str, kind: str) -> dict[str, Any]:
    case_root = work_root / name
    source = case_root / "source"
    landing = case_root / "landing"
    if kind in {"receive", "run", "timeout", "usage"}:
        source.mkdir(parents=True, exist_ok=True)
        (source / "clip.mov").write_bytes(b"video")

    if kind == "receive":
        argv = [
            "--fake-source",
            str(source),
            "--landing",
            str(landing),
            "--source-kind",
            "card",
            "--operator",
            "Op",
            "--json",
        ]
    elif kind == "run":
        argv = [
            "run",
            "--fake-source",
            str(source),
            "--landing",
            str(landing),
            "--source-kind",
            "card",
            "--operator",
            "Op",
            "--json",
        ]
    elif kind == "timeout":
        argv = [
            "--fake-source",
            str(source),
            "--landing",
            str(landing),
            "--source-kind",
            "card",
            "--operator",
            "Op",
            "--confirm-timeout",
            "0",
            "--json",
        ]
    elif kind == "usage":
        fake = case_root / "fake"
        fake.mkdir(parents=True, exist_ok=True)
        argv = [
            str(source),
            "--fake-source",
            str(fake),
            "--landing",
            str(landing),
            "--source-kind",
            "card",
            "--operator",
            "Op",
        ]
    elif kind in {"sweep", "sweep-orphans"}:
        _write_sweep_fixture(landing)
        argv = [
            kind,
            "--landing",
            str(landing),
            "--older-than-hours",
            "24",
            "--json",
        ]
    else:
        raise AssertionError(kind)

    exit_code, stdout, stderr = _run_receive_cli(argv)
    stdout_payload = _json_or_none(stdout)
    intake_id = (
        str(stdout_payload["intake_id"])
        if isinstance(stdout_payload, dict) and "intake_id" in stdout_payload
        else None
    )
    return {
        "name": name,
        "argv": _normalize_json(
            argv,
            work_root=work_root,
            source=source,
            landing=landing,
            intake_id=intake_id,
        ),
        "exit_code": exit_code,
        "stdout": _normalize_text(
            stdout,
            work_root=work_root,
            source=source,
            landing=landing,
            intake_id=intake_id,
        ),
        "stderr": _normalize_text(
            stderr,
            work_root=work_root,
            source=source,
            landing=landing,
            intake_id=intake_id,
        ),
        "stdout_json": _normalize_json(
            stdout_payload,
            work_root=work_root,
            source=source,
            landing=landing,
            intake_id=intake_id,
        ),
    }


def _confirmation_rendering_cases(work_root: Path) -> list[dict[str, Any]]:
    result = receive_core.ReceiveResult(
        intake_id="fixture-intake",
        intake_dir=work_root / "landing" / "fixture-intake",
        manifest_path=work_root / "landing" / "fixture-intake" / "manifest-sha256.txt",
        bag_info_path=work_root / "landing" / "fixture-intake" / "bag-info.txt",
        tagmanifest_path=work_root / "landing" / "fixture-intake" / "tagmanifest-sha256.txt",
        sentinel_path=work_root / "landing" / "fixture-intake" / "intake.json",
        file_count=1,
        total_bytes=5,
        skipped_count=0,
        bag_profile=BAG_PROFILE,
    )
    confirmations = [
        receive_core.ConfirmationResult(True, "verified", work_root / "verified.json", {"ok": True}),
        receive_core.ConfirmationResult(False, "pending", work_root / "verified.json", None),
        receive_core.ConfirmationResult(
            False,
            "quarantined",
            work_root / "intake.quarantined.json",
            {"reason": "bag-invalid"},
        ),
        receive_core.ConfirmationResult(
            False,
            "discrepancy",
            work_root / "intake.discrepancy.json",
            {"details": {"missing": ["clip.mov"]}},
        ),
        receive_core.ConfirmationResult(False, "timeout", None, None),
    ]
    cases = []
    for confirmation in confirmations:
        stdout_lines, stderr_lines = receive_cli.receive_text_lines(result, confirmation)
        cases.append(
            {
                "status": confirmation.status,
                "payload": _normalize_json(
                    receive_cli.receive_result_payload(result, confirmation),
                    work_root=work_root,
                    source=None,
                    landing=work_root / "landing",
                    intake_id=result.intake_id,
                ),
                "stdout_lines": _normalize_json(
                    stdout_lines,
                    work_root=work_root,
                    source=None,
                    landing=work_root / "landing",
                    intake_id=result.intake_id,
                ),
                "stderr_lines": _normalize_json(
                    stderr_lines,
                    work_root=work_root,
                    source=None,
                    landing=work_root / "landing",
                    intake_id=result.intake_id,
                ),
                "exit_code": 0 if confirmation.release_ok else 3,
            }
        )
    return cases


def _snapshot_bag_files(
    intake_dir: Path,
    *,
    work_root: Path,
    source: Path,
    landing: Path,
    intake_id: str,
) -> list[dict[str, Any]]:
    records = []
    for path in sorted(item for item in intake_dir.rglob("*") if item.is_file()):
        relpath = path.relative_to(intake_dir).as_posix()
        if relpath == "receive.log":
            continue
        if relpath in TEXT_BAG_FILES:
            records.append(
                {
                    "path": relpath,
                    "kind": "text",
                    "text": _normalize_text(
                        path.read_text(encoding="utf-8"),
                        work_root=work_root,
                        source=source,
                        landing=landing,
                        intake_id=intake_id,
                    ),
                }
            )
        else:
            records.append(
                {
                    "path": relpath,
                    "kind": "bytes",
                    "sha256": _sha256_file(path),
                    "size": path.stat().st_size,
                }
            )
    return records


