def write_corpus(corpus: Mapping[str, Any], fixture_root: Path = DEFAULT_FIXTURE_ROOT) -> None:
    """Write a generated corpus to the fixture directory."""

    fixture_root.mkdir(parents=True, exist_ok=True)
    (fixture_root / "README.md").write_text(
        "\n".join(
            [
                "# sutradhara-receive conformance fixtures",
                "",
                "Generated by `packages/sutradhara-receive/scripts/extract_fixtures.py`.",
                "These files snapshot the current Python receive contract before the",
                "Rust receive-core migration. Update them only by intentionally running",
                "the extractor after a reviewed contract change.",
                "",
            ]
        ),
        encoding="utf-8",
    )
    for name, payload in corpus.items():
        _write_json(fixture_root / f"{name}.json", payload)


def load_committed_corpus(fixture_root: Path = DEFAULT_FIXTURE_ROOT) -> dict[str, Any]:
    """Load all committed JSON fixtures."""

    return {
        path.stem: json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(fixture_root.glob("*.json"))
    }


def public_api_snapshot() -> dict[str, Any]:
    """Describe the Python import surface the PyO3 wheel must preserve."""

    dataclass_shapes: dict[str, Any] = {}
    class_bases: dict[str, list[str]] = {}
    top_level_functions: dict[str, str] = {}
    top_level_constants: dict[str, Any] = {}
    for name in sutradhara_receive.__all__:
        value = getattr(sutradhara_receive, name)
        if inspect.isclass(value):
            class_bases[name] = [_qualified_name(base) for base in value.__bases__]
            if dataclasses.is_dataclass(value):
                dataclass_shapes[name] = _dataclass_shape(value)
            continue
        if callable(value):
            top_level_functions[name] = str(inspect.signature(value))
            continue
        top_level_constants[name] = _jsonable(value)

    return {
        "schema_version": 1,
        "module": "sutradhara_receive",
        "__all__": list(sutradhara_receive.__all__),
        "__all_count": len(sutradhara_receive.__all__),
        "constants": top_level_constants,
        "functions": top_level_functions,
        "classes": class_bases,
        "dataclasses": dataclass_shapes,
        "member_name_exports": _module_defined_exports(member_name),
        "member_name_signatures": _module_signatures(member_name),
        "cli_exports": _module_defined_exports(receive_cli),
        "cli_signatures": _module_signatures(receive_cli),
        "cli_json_schema": {
            "receive_required_keys": [
                "bag_info_path",
                "bag_profile",
                "file_count",
                "intake_dir",
                "intake_id",
                "manifest_path",
                "sentinel_path",
                "skipped_count",
                "tagmanifest_path",
                "total_bytes",
            ],
            "confirmation_keys": ["detail", "marker_path", "release_ok", "status"],
            "sweep_required_keys": ["removed"],
        },
    }


def string_fixtures(work_root: Path) -> dict[str, Any]:
    """Build escaping and canonicalization fixture vectors."""

    root = work_root / "root"
    root.mkdir(parents=True, exist_ok=True)
    escape_cases = [
        ("ascii", b"clip.mov"),
        ("utf8_nfc", "Caf\u00e9.mov".encode("utf-8")),
        ("utf8_nfd", b"Cafe\xcc\x81.mov"),
        ("backslash", b"dir\\name.mov"),
        ("control", b"line\nfeed\x7f.mov"),
        ("invalid_utf8", b"\xffbad\xc3(.mov"),
        ("unassigned_codepoint", "\u0378.txt".encode("utf-8")),
    ]
    canonical_fs_cases = [
        ("nfd_to_nfc", [b"Cafe\xcc\x81.mov"]),
        ("invalid_utf8", [b"\xff.bin"]),
        ("nested", [b"Folder", b"clip.mov"]),
        ("backslash", [b"we\\ird.mov"]),
        ("control", [b"a\nb.mov"]),
        ("unassigned_codepoint", ["\u0378.txt".encode("utf-8")]),
    ]
    manifest_cases = [
        "./data/Cafe\u0301.mov",
        "/data/clip.mov",
        r"data/\xff.bin",
        r"data/we\\ird.mov",
    ]
    manifest_rejections = ["", "..", "data/../x", r"data/bad\q"]
    return {
        "schema_version": 1,
        "escape_member_name": [
            {
                "name": name,
                "raw_hex": raw.hex(),
                "escaped": escape_member_name(raw),
                "roundtrip_hex": unescape_member_name(escape_member_name(raw)).hex(),
            }
            for name, raw in escape_cases
        ],
        "canonicalize_filesystem_path": [
            {
                "name": name,
                "components_hex": [component.hex() for component in components],
                "canonical": receive_core.canonicalize_filesystem_path(
                    _path_from_raw_components(root, components),
                    root,
                ),
            }
            for name, components in canonical_fs_cases
        ],
        "canonicalize_manifest_path": [
            {"raw": raw, "canonical": receive_core.canonicalize_manifest_path(raw)}
            for raw in manifest_cases
        ],
        "canonicalize_manifest_rejections": [
            {
                "raw": raw,
                "error": _raises_message(lambda raw=raw: receive_core.canonicalize_manifest_path(raw)),
            }
            for raw in manifest_rejections
        ],
    }


