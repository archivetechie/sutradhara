def _write_package_fixture(package_root: Path) -> None:
    (package_root / "Render").mkdir(parents=True, exist_ok=True)
    (package_root / "Render" / "clip01.mov").write_bytes(b"clip-one")
    (package_root / "Render" / "clip02.mov").write_bytes(b"clip-two")
    _write_raw_named_file(package_root / "Render", b"\xfelegacy.dat", b"legacy")
    (package_root / "._meta").write_bytes(b"appledouble")
    (package_root / "library.plist").write_bytes(b"plist")
    link = package_root / "clip-link.mov"
    with contextlib.suppress(FileExistsError):
        link.symlink_to("Render/clip01.mov")


def _write_sweep_fixture(landing: Path) -> None:
    stale = landing / "stale"
    fresh = landing / "fresh"
    complete = landing / "complete"
    for path in (stale, fresh, complete):
        path.mkdir(parents=True, exist_ok=True)
        (path / ".receiving.json").write_text("{}", encoding="utf-8")
    (complete / "intake.json").write_text("{}", encoding="utf-8")
    old = dt.datetime.now().timestamp() - 48 * 3600
    os.utime(stale / ".receiving.json", (old, old))


def _run_receive_cli(argv: list[str]) -> tuple[int, str, str]:
    stdout = io.StringIO()
    stderr = io.StringIO()
    with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
        exit_code = receive_cli.main(argv)
    return exit_code, stdout.getvalue(), stderr.getvalue()


def _path_from_raw_components(root: Path, components: Iterable[bytes]) -> Path:
    path = root
    for component in components:
        path = path / os.fsdecode(component)
    return path


def _write_raw_named_file(parent: Path, raw_name: bytes, data: bytes) -> None:
    parent.mkdir(parents=True, exist_ok=True)
    raw_parent = os.fsencode(parent)
    raw_path = raw_parent + os.sep.encode() + raw_name
    fd = os.open(raw_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o644)
    try:
        os.write(fd, data)
    finally:
        os.close(fd)


def _normalize_text(
    text: str,
    *,
    work_root: Path,
    source: Path | None,
    landing: Path | None,
    intake_id: str | None,
) -> str:
    replacements = [(str(work_root), "<FIXTURE-ROOT>")]
    if source is not None:
        replacements.append((str(source), "<SOURCE>"))
    if landing is not None:
        replacements.append((str(landing), "<LANDING>"))
    if intake_id is not None:
        replacements.append((intake_id, "<INTAKE-ID>"))
    normalized = text
    for old, new in sorted(replacements, key=lambda item: len(item[0]), reverse=True):
        normalized = normalized.replace(old, new)
    return normalized


def _normalize_json(
    value: Any,
    *,
    work_root: Path,
    source: Path | None,
    landing: Path | None,
    intake_id: str | None,
) -> Any:
    if isinstance(value, str):
        return _normalize_text(
            value,
            work_root=work_root,
            source=source,
            landing=landing,
            intake_id=intake_id,
        )
    if isinstance(value, list):
        return [
            _normalize_json(
                item,
                work_root=work_root,
                source=source,
                landing=landing,
                intake_id=intake_id,
            )
            for item in value
        ]
    if isinstance(value, dict):
        return {
            key: _normalize_json(
                item,
                work_root=work_root,
                source=source,
                landing=landing,
                intake_id=intake_id,
            )
            for key, item in value.items()
        }
    return value


def _json_or_none(text: str) -> Any | None:
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        return None


def _raises_message(callback: Callable[[], Any]) -> str:
    try:
        callback()
    except Exception as exc:
        return str(exc)
    raise AssertionError("callback did not raise")


def _dataclass_shape(cls: type[Any]) -> dict[str, Any]:
    return {
        "fields": [
            {
                "name": field.name,
                "default": _field_default(field),
            }
            for field in dataclasses.fields(cls)
        ],
        "properties": sorted(
            name for name, value in vars(cls).items() if isinstance(value, property)
        ),
        "methods": {
            name: str(inspect.signature(value))
            for name, value in sorted(vars(cls).items())
            if callable(value) and not name.startswith("_")
        },
    }


def _field_default(field: dataclasses.Field[Any]) -> Any:
    if field.default is not dataclasses.MISSING:
        return _jsonable(field.default)
    if field.default_factory is not dataclasses.MISSING:  # type: ignore[comparison-overlap]
        return "<factory>"
    return "<required>"


def _module_defined_exports(module: Any) -> list[str]:
    exports = []
    for name in dir(module):
        if name.startswith("_"):
            continue
        value = getattr(module, name)
        if getattr(value, "__module__", None) == module.__name__ or name.isupper():
            exports.append(name)
    return sorted(exports)


def _module_signatures(module: Any) -> dict[str, str]:
    signatures = {}
    for name in _module_defined_exports(module):
        value = getattr(module, name)
        if inspect.isclass(value) or callable(value):
            with contextlib.suppress(TypeError, ValueError):
                signatures[name] = str(inspect.signature(value))
    return signatures


def _qualified_name(value: Any) -> str:
    return f"{value.__module__}.{value.__qualname__}"


def _jsonable(value: Any) -> Any:
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, tuple):
        return [_jsonable(item) for item in value]
    if isinstance(value, frozenset):
        return sorted(_jsonable(item) for item in value)
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    return repr(value)


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _write_json(path: Path, payload: Any) -> None:
    path.write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def main(argv: list[str] | None = None) -> int:
    """Generate and write the receive fixture corpus."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_FIXTURE_ROOT,
        help="Fixture directory to write. Defaults to the package fixture dir.",
    )
    args = parser.parse_args(argv)
    with tempfile.TemporaryDirectory(prefix="receive-fixtures-") as raw_tmp:
        work_root = Path(raw_tmp)
        corpus = build_corpus(work_root)
    if args.output.exists():
        shutil.rmtree(args.output)
    write_corpus(corpus, args.output)
    return 0


